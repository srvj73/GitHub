function CheckPackage() {
    $pkg = Join-Path $Downloads $PackageName
    if (-not (Test-Path -LiteralPath $pkg -PathType Leaf)) { throw ('PACKAGE_NOT_FOUND=' + $pkg) }
    $s = Sha $pkg
    if ($s -cne $ExpectedPackageSha) { throw ('PACKAGE_SHA_MISMATCH=' + $s) }
    Log ('PACKAGE=' + $pkg + ' SHA256_OK=' + $s)
    return $pkg
}
function ExtractFrozen([string]$Pkg, [string]$Dest, $Members) {
    # Autoextracao segura: cada membro conferido contra o RUNTIME_CODE_MANIFEST do pacote E contra o pin deste launcher;
    # criacao exclusiva (nunca sobrescreve); releitura do arquivo gravado.
    Add-Type -AssemblyName System.IO.Compression
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    $zip = [IO.Compression.ZipFile]::OpenRead($Pkg)
    try {
        $me = $zip.GetEntry('implementation_v001/RUNTIME_CODE_MANIFEST.json')
        if ($null -eq $me) { throw 'RUNTIME_MANIFEST_ABSENT' }
        $ms = $me.Open(); $buf = New-Object IO.MemoryStream
        try { $ms.CopyTo($buf) } finally { $ms.Dispose() }
        $mraw = $buf.ToArray()
        if ((ShaBytes $mraw) -cne $ExpectedRuntimeManifestSha) { throw 'RUNTIME_MANIFEST_SHA' }
        $manifest = $Utf8.GetString($mraw) | ConvertFrom-Json
        $rows = @{}
        foreach ($r in $manifest.files) { $rows[[string]$r.path] = ([string]$r.sha256).ToUpperInvariant() }
        foreach ($rel in $Members.Keys) {
            $pin = [string]$Members[$rel]
            if (-not $rows.ContainsKey($rel) -or $rows[$rel] -cne $pin) { throw ('MANIFEST_PIN_DIVERGES=' + $rel) }
            $entry = $zip.GetEntry('implementation_v001/candidate/' + $rel)
            if ($null -eq $entry) { throw ('MEMBER_ABSENT=' + $rel) }
            $target = Join-Path $Dest ($rel -replace '/', '\')
            New-Item -ItemType Directory -Path ([IO.Path]::GetDirectoryName($target)) -Force | Out-Null
            [IO.Compression.ZipFileExtensions]::ExtractToFile($entry, $target, $false)
            if ((Sha $target) -cne $pin) { throw ('EXTRACTED_SHA_MISMATCH=' + $rel) }
            Log ('EXTRAIDO=' + $rel + ' SHA256=' + $pin)
        }
    } finally { $zip.Dispose() }
}
function Unpack([string]$B64, [string]$Expected, [string]$Path) {
    $bytes = [Convert]::FromBase64String(($B64 -replace '\s', ''))
    if ((ShaBytes $bytes) -cne $Expected) { throw ('EMBEDDED_SHA_MISMATCH=' + $Path) }
    [IO.File]::WriteAllBytes($Path, $bytes)
    if ((Sha $Path) -cne $Expected) { throw ('EMBEDDED_READBACK_MISMATCH=' + $Path) }
    Log ('UNPACKED=' + $Path + ' SHA256=' + $Expected)
}
